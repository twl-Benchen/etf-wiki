"""互動測試：鍵盤走路、V 切換視角、點店家自動走過去並打開卡片、手機觸控 (搖桿與收合)。
用法：python interact.py 輸出資料夾"""
import os, sys, json
from playwright.sync_api import sync_playwright
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from run import open_page
out = sys.argv[1]; os.makedirs(out, exist_ok=True)
ok = lambda c, m: print(("通過" if c else "失敗") + "｜" + m)
with sync_playwright() as p:
    b, pg, errs = open_page(p, 1366, 768)
    m0 = pg.evaluate("__city.me()")
    pg.mouse.click(300, 300)   # 讓畫面取得焦點 (點到地面會走過去，先等它走完)
    pg.wait_for_timeout(2500)
    m0 = pg.evaluate("__city.me()")
    pg.keyboard.down("w"); pg.wait_for_timeout(1200); pg.keyboard.up("w")
    m1 = pg.evaluate("__city.me()")
    ok(abs(m1["z"] - m0["z"]) + abs(m1["x"] - m0["x"]) > 0.8, f"按 W 會往前走 ({m0['x']:.1f},{m0['z']:.1f}) → ({m1['x']:.1f},{m1['z']:.1f})")
    pg.keyboard.press("v"); pg.wait_for_timeout(300); ok(pg.evaluate("__city.me().view") == "fp", "按 V 切到眼睛視角")
    pg.keyboard.press("v"); pg.wait_for_timeout(300); ok(pg.evaluate("__city.me().view") == "tp", "再按 V 切回背後視角")
    pg.evaluate("__city.teleport('鴻海')"); pg.evaluate("__city.look(__city.me().yaw + 1.57, 0.1)"); pg.wait_for_timeout(800)
    x, y = pg.evaluate("__city.screenOf('大立光')")
    pg.mouse.click(x, y); pg.wait_for_timeout(200)
    ok(pg.evaluate("__city.me().auto"), f"點大立光招牌 ({x:.0f},{y:.0f}) 會開始自動走路")
    pg.evaluate("__city.sim(360)")   # 直接推進 6 秒的遊戲時間 (模擬顯示卡畫面太慢)
    pg.wait_for_function("!__city.me().auto", timeout=30000); pg.wait_for_timeout(500)
    card = pg.evaluate("!document.getElementById('card').hidden && document.querySelector('#card b').textContent")
    ok(card == "大立光", f"走到之後打開店家卡片：{card}")
    pg.screenshot(path=os.path.join(out, "click_card.png"))
    pg.keyboard.press("Escape"); pg.keyboard.press("m"); pg.wait_for_timeout(400)
    ok(pg.evaluate("!document.getElementById('mapDlg').hidden"), "按 M 打開導覽圖")
    pg.keyboard.press("m")
    pg.keyboard.down("s"); pg.evaluate("__city.sim(400)"); pg.keyboard.up("s")
    me = pg.evaluate("__city.me()")
    ok(pg.evaluate(f"walkable_check={json.dumps(me)}, true"), f"一直往後走不會穿牆，停在 ({me['x']:.1f},{me['z']:.1f})")
    print("ERRORS:", errs); b.close()
    # 手機觸控
    br, pg, errs2 = open_page(p, 390, 844, has_touch=True, is_mobile=True, device_scale_factor=2)
    ctx = pg.context
    ok(pg.evaluate("!document.getElementById('joy').hidden"), "手機顯示搖桿")
    jb = pg.evaluate("(()=>{const r=document.getElementById('joy').getBoundingClientRect();return [r.left+r.width/2,r.top+r.height/2]})()")
    m0 = pg.evaluate("__city.me()")
    cdp = ctx.new_cdp_session(pg)
    cdp.send("Input.dispatchTouchEvent", {"type": "touchStart", "touchPoints": [{"x": jb[0], "y": jb[1], "id": 1}]})
    for i in range(10): cdp.send("Input.dispatchTouchEvent", {"type": "touchMove", "touchPoints": [{"x": jb[0], "y": jb[1] - 4 * i, "id": 1}]}); pg.wait_for_timeout(60)
    pg.wait_for_timeout(1200)
    cdp.send("Input.dispatchTouchEvent", {"type": "touchEnd", "touchPoints": []})
    m1 = pg.evaluate("__city.me()")
    ok(abs(m1["z"] - m0["z"]) + abs(m1["x"] - m0["x"]) > 0.5, f"搖桿往上推會往前走 ({m0['z']:.1f} → {m1['z']:.1f})")
    pg.screenshot(path=os.path.join(out, "touch.png"))
    pg.evaluate("document.getElementById('chatMini').click()"); pg.wait_for_timeout(600)
    pg.screenshot(path=os.path.join(out, "touch_mini.png"))
    print("ERRORS:", errs2); br.close()
